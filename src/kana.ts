/**
 * ひらがな・カタカナ・全角半角の違いを無視して検索するための正規化と、
 * 漢字名の読み（ひらがな）。
 */
export function normalize(s: string): string {
  return (s || "")
    .normalize("NFKC")
    .toLowerCase()
    // カタカナ → ひらがな
    .replace(/[ァ-ヶ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    .replace(/[ヽヾ]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0x60))
    // 区切り記号・空白を除く
    .replace(/[\s・･\-‐－_.。、,!！?？「」【】#＃]/g, "");
}

